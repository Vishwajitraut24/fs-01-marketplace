import mongoose from "mongoose";
import PDFDocument from "pdfkit";

import { OrderModel } from "../models/order.model.js";
import { AppError } from "../middleware/app-error.js";

function formatINR(paise: number): string {
  return new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
  }).format(paise / 100);
}

export async function generateCustomerInvoice(
  userId: string,
  orderId: string,
): Promise<Buffer> {
  if (!mongoose.isValidObjectId(orderId)) {
    throw new AppError(
      400,
      "INVALID_ORDER_ID",
      "Invalid order ID.",
    );
  }

  const order = await OrderModel.findOne({
    _id: orderId,
    customer: userId,
  }).lean();

  if (!order) {
    throw new AppError(
      404,
      "ORDER_NOT_FOUND",
      "Order not found.",
    );
  }

  if (
    order.status === "PENDING_PAYMENT" ||
    order.status === "CANCELLED"
  ) {
    throw new AppError(
      409,
      "INVOICE_NOT_AVAILABLE",
      "Invoice is unavailable for this order status.",
    );
  }

  return new Promise((resolve, reject) => {
    const document = new PDFDocument({
      size: "A4",
      margin: 45,
      bufferPages: true,
    });

    const chunks: Buffer[] = [];

    document.on("data", (chunk: Buffer) => {
      chunks.push(chunk);
    });

    document.on("end", () => {
      resolve(Buffer.concat(chunks));
    });

    document.on("error", reject);

    // HEADER
    document
      .fontSize(22)
      .font("Helvetica-Bold")
      .text("FS-01 MARKETPLACE");

    document
      .fontSize(16)
      .text("ORDER INVOICE", { align: "right" });

    document.moveDown();

    document
      .fontSize(10)
      .font("Helvetica")
      .text(`Invoice Number: FS01-${order.orderNumber}`)
      .text(`Order Number: ${order.orderNumber}`)
      .text(`Order Date: ${order.createdAt.toDateString()}`)
      .text(`Payment Method: ${order.payment.method}`)
      .text(`Payment Status: ${order.payment.status}`);

    document.moveDown();

    // SHIPPING ADDRESS
    document
      .fontSize(12)
      .font("Helvetica-Bold")
      .text("SHIPPING ADDRESS");

    document
      .fontSize(10)
      .font("Helvetica")
      .text(order.shippingAddress.fullName)
      .text(order.shippingAddress.phone)
      .text(order.shippingAddress.addressLine1);

    if (order.shippingAddress.addressLine2) {
      document.text(order.shippingAddress.addressLine2);
    }

    document.text(
      `${order.shippingAddress.city}, ${order.shippingAddress.state} - ${order.shippingAddress.postalCode}`,
    );

    document.text(order.shippingAddress.country);

    document.moveDown();

    // ITEMS
    document
      .fontSize(12)
      .font("Helvetica-Bold")
      .text("ORDER ITEMS");

    document.moveDown(0.5);

    for (const sellerOrder of order.sellerOrders) {
      document
        .fontSize(11)
        .font("Helvetica-Bold")
        .text(`Seller: ${sellerOrder.storeName}`);

      for (const item of sellerOrder.items) {
        document
          .fontSize(9)
          .font("Helvetica")
          .text(item.productName);

        document.text(
          `SKU: ${item.sku} | Quantity: ${item.quantity} | Unit Price: ${formatINR(item.unitPricePaise)} | Total: ${formatINR(item.lineTotalPaise)}`,
        );

        document.moveDown(0.5);
      }
    }

    document.moveDown();

    // TOTALS
    document
      .fontSize(11)
      .font("Helvetica-Bold")
      .text("PAYMENT SUMMARY");

    document
      .fontSize(10)
      .font("Helvetica")
      .text(`Subtotal: ${formatINR(order.subtotalPaise)}`)
      .text(`Shipping: ${formatINR(order.shippingFeePaise)}`)
      .text(`Discount: ${formatINR(order.discountPaise)}`);

    if (order.couponCode) {
      document.text(`Coupon Applied: ${order.couponCode}`);
    }

    document
      .moveDown()
      .fontSize(14)
      .font("Helvetica-Bold")
      .text(`GRAND TOTAL: ${formatINR(order.totalPaise)}`);

    document.moveDown(2);

    document
      .fontSize(8)
      .font("Helvetica")
      .text(
        "This document is an order invoice generated by FS-01 Marketplace. It is not a GST tax invoice.",
      );

    document
      .moveDown()
      .text("Thank you for shopping with FS-01 Marketplace!");

    document.end();
  });
}